local function detect()
    -- Same native localisation lookup used by TheGathering. Do not compile
    -- global UI expressions during toolbar creation or first-tick bootstrap.
    local ok,value=pcall(function()
        return effect.get_localised_string("names_name_2012172474")
    end)
    if not ok or type(value)~="string" then return nil end
    if value=="刘" or value=="劉" then return "zh" end
    if value=="유" then return "ko" end
    if value=="Liu" then return "en" end
    -- Japanese remains selectable explicitly; its surname can match Chinese.
    return nil
end

function M.language()
    if M.override then return M.override end
    if M.current == nil then M.current = detect() or "zh" end
    return M.current
end

function M.next_language()
    local list = M.override and {} or {}
    for _, code in ipairs(order) do list[#list + 1] = code end
    local current = M.language()
    for i, code in ipairs(list) do
        if code == current then
            local nxt = list[i % #list + 1]
            M.override = nxt
            if TK_AUTO_TOOLBAR then TK_AUTO_TOOLBAR.language(nxt) end
            return nxt
        end
    end
    M.override = list[1]
    return M.override
end

function M.get(key)
    local lang = M.language()
    local table_for = M.strings[lang] or M.strings.en
    local value = table_for[key]
    if value == nil then value = M.strings.en[key] end
    if value == nil then value = M.strings.zh[key] end
    return value or tostring(key)
end

function M.label(code)
    if code == "zh" then return "中文" end
    if code == "en" then return "English" end
    if code == "ko" then return "한국어" end
    if code == "ja" then return "日本語" end
    return tostring(code)
end

-- Settlement/army status codes are internal identifiers, not player-facing text.
-- Map them through the same tables, falling back to the bare code so an unmapped
-- one still reads sensibly instead of arriving as "reason_xxx".
function M.reason(code)
    local text = tostring(code or "unknown")
    local key = "reason_" .. text
    local value = M.get(key)
    if value == key then return M.get("reason_unknown") end
    return value
end

-- Short alias used everywhere in the two mods.
function K.L(key) return M.get(key) end

function K.reason(code) return M.reason(code) end
